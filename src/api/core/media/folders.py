"""Build safe Cloudinary asset-folder paths from trusted server-side records."""

import re
import uuid

from django.conf import settings


_RESOURCE_LAYOUTS = {
    "student": ("hoc-vien", "site"),
    "teacher": ("giao-vien", "site"),
    "account": ("tai-khoan", "shared"),
    "course": ("khoa-hoc", "shared"),
    "branch": ("co-so", "shared"),
    "brand": ("thuong-hieu", "shared"),
}
_SITE_CODE = re.compile(r"[A-Z0-9_-]{2,12}\Z")
_RECORD_CODE = re.compile(r"[A-Z0-9][A-Z0-9_-]{0,63}\Z")
_FOLDER_SEGMENT = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}\Z")


def _validate_code(value: str, pattern: re.Pattern[str], label: str) -> str:
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise ValueError(f"{label} không hợp lệ.")
    return value


def build_asset_folder(
    resource_type: str,
    *,
    asset_id: str,
    record_code: str,
    site_code: str | None = None,
) -> str:
    """Return the Cloudinary folder path for one image asset.

    ``asset_id`` must be a UUID generated by the API. Site-specific photos
    require a trusted site code; shared catalog photos deliberately omit it.
    The caller must derive all identifiers from authorized server-side data,
    never directly from an untrusted request body.
    """

    layout = _RESOURCE_LAYOUTS.get(resource_type)
    if layout is None:
        raise ValueError("Loại tài nguyên ảnh không được hỗ trợ.")

    category, scope = layout
    record_code = _validate_code(record_code, _RECORD_CODE, "Mã hồ sơ")

    root_folder = settings.CLOUDINARY_ROOT_FOLDER.strip("/ ")
    root_segments = root_folder.split("/")
    if not root_segments or any(not _FOLDER_SEGMENT.fullmatch(part) for part in root_segments):
        raise ValueError("CLOUDINARY_ROOT_FOLDER không hợp lệ.")

    if scope == "site":
        if site_code is None:
            raise ValueError("Ảnh hồ sơ theo cơ sở cần có mã site đã xác thực.")
        site_code = _validate_code(site_code, _SITE_CODE, "Mã cơ sở")
        scope_segments = [site_code, record_code]
    else:
        if site_code is not None:
            raise ValueError("Ảnh dùng chung không được gắn vào một site riêng.")
        scope_segments = ["dung-chung", record_code]

    try:
        parsed_asset_id = uuid.UUID(asset_id)
    except (AttributeError, TypeError, ValueError) as exc:
        raise ValueError("Mã ảnh phải là UUID do API tạo.") from exc

    if parsed_asset_id.version != 4:
        raise ValueError("Mã ảnh phải là UUID phiên bản 4 do API tạo.")

    return "/".join(
        [*root_segments, category, *scope_segments, "anh", str(parsed_asset_id)]
    )
