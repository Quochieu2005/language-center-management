"""Build safe Cloudinary asset-folder paths from trusted server-side records."""

import re
import uuid

from django.conf import settings


_RESOURCE_LAYOUTS = {
    "student": ("hoc-vien", "site"),
    "teacher": ("giao-vien", "site"),
    "employee": ("nhan-vien", "site"),
    "account": ("admin", "shared"),
    "user": ("nguoi-dung", "shared"),
    "course": ("khoa-hoc", "shared"),
    "branch": ("co-so", "shared"),
    "brand": ("thuong-hieu", "shared"),
}
_SITE_CODE = re.compile(r"[A-Z0-9_-]{2,12}\Z")
_RECORD_CODE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}\Z")
_FOLDER_SEGMENT = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}\Z")


def _validate_code(value: str, pattern: re.Pattern[str], label: str) -> str:
    if not isinstance(value, str) or not pattern.fullmatch(value):
        raise ValueError(f"{label} không hợp lệ.")
    return value


def build_asset_folder(
    resource_type: str,
    *,
    asset_id: str,
    record_code: str,
    site_code: str | None = None,
) -> str:
    """Return the Cloudinary folder path for one image asset.

    ``asset_id`` must be a UUID generated by the API. Site-specific photos
    require a trusted site code; shared catalog photos deliberately omit it.
    The caller must derive all identifiers from authorized server-side data,
    never directly from an untrusted request body.
    """

    layout = _RESOURCE_LAYOUTS.get(resource_type)
    if layout is None:
        raise ValueError("Loại tài nguyên ảnh không được hỗ trợ.")

    category, scope = layout
    record_code = _validate_code(record_code, _RECORD_CODE, "Mã hồ sơ")

    root_folder = settings.CLOUDINARY_ROOT_FOLDER.strip("/ ")
    root_segments = root_folder.split("/")
    if not root_segments or any(not _FOLDER_SEGMENT.fullmatch(part) for part in root_segments):
        raise ValueError("CLOUDINARY_ROOT_FOLDER không hợp lệ.")

    if scope == "site":
        if site_code is None:
            raise ValueError("Ảnh hồ sơ theo cơ sở cần có mã site đã xác thực.")
        site_code = _validate_code(site_code, _SITE_CODE, "Mã cơ sở")
        scope_segments = [site_code, record_code]
    else:
        if site_code is not None:
            raise ValueError("Ảnh dùng chung không được gắn vào một site riêng.")
        scope_segments = [record_code] if resource_type == "account" else ["dung-chung", record_code]

    try:
        parsed_asset_id = uuid.UUID(asset_id)
    except (AttributeError, TypeError, ValueError) as exc:
        raise ValueError("Mã ảnh phải là UUID do API tạo.") from exc

    if parsed_asset_id.version != 4:
        raise ValueError("Mã ảnh phải là UUID phiên bản 4 do API tạo.")

    return "/".join(
        [*root_segments, category, *scope_segments, "anh", str(parsed_asset_id)]
    )


_LEGACY_UUID_PUBLIC_ID = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\Z")
_PATH_PUBLIC_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]*(?:/[A-Za-z0-9][A-Za-z0-9_-]*){1,7}\Z")
_AVATAR_RESOURCES = {"student", "teacher", "employee", "account", "user"}


def _root_segments() -> list[str]:
    root_folder = settings.CLOUDINARY_ROOT_FOLDER.strip("/ ")
    segments = root_folder.split("/")
    if not segments or any(not _FOLDER_SEGMENT.fullmatch(part) for part in segments):
        raise ValueError("CLOUDINARY_ROOT_FOLDER không hợp lệ.")
    return segments


def build_avatar_public_id(resource_type: str, *, slug: str, on_date, site_code: str | None = None) -> tuple[str, str]:
    """Return ``(asset_folder, public_id)`` for a profile photo.

    Layout: ``<root>/<admin|giao-vien|nhan-vien|hoc-vien>[/<SITE>]/<slug>-<dd-mm-yyyy>``.
    The slug is the server-side profile/account slug (unique per account, or per site
    for students, which also carry the site segment), so the name only repeats when the
    same person uploads again on the same day; that upload replaces the day's photo.
    """
    if resource_type not in _AVATAR_RESOURCES:
        raise ValueError("Loại ảnh đại diện không được hỗ trợ.")
    category, scope = _RESOURCE_LAYOUTS[resource_type]
    segments = [*_root_segments(), category]
    if scope == "site":
        if site_code is None:
            raise ValueError("Ảnh hồ sơ theo cơ sở cần có mã site đã xác thực.")
        segments.append(_validate_code(site_code, _SITE_CODE, "Mã cơ sở"))
    elif site_code is not None:
        raise ValueError("Ảnh tài khoản quản trị không gắn vào một site riêng.")
    name = _validate_code(f"{slug}-{on_date:%d-%m-%Y}", _RECORD_CODE, "Tên ảnh")
    folder = "/".join(segments)
    return folder, f"{folder}/{name}"


def build_blog_image_public_id(kind: str, *, slug: str, on_date, stamp: str) -> tuple[str, str]:
    """Return ``(asset_folder, public_id)`` for a Blog image.

    Layout: ``<root>/blog/bia/<slug>-<dd-mm-yyyy>`` for the cover (one per article per day) and
    ``<root>/blog/noi-dung/<slug>-<HHMMSS>-<dd-mm-yyyy>`` for pictures inside the article body.
    """
    if kind not in {"cover", "content"}:
        raise ValueError("Loại ảnh Blog không được hỗ trợ.")
    folder = "/".join([*_root_segments(), "blog", "bia" if kind == "cover" else "noi-dung"])
    suffix = f"{on_date:%d-%m-%Y}" if kind == "cover" else f"{stamp}-{on_date:%d-%m-%Y}"
    name = _validate_code(f"{slug}-{suffix}", _RECORD_CODE, "Tên ảnh")
    return folder, f"{folder}/{name}"


def is_blog_public_id(value: object) -> bool:
    if not isinstance(value, str) or not _PATH_PUBLIC_ID.fullmatch(value):
        return False
    base = "/".join(_root_segments()) + "/blog/"
    return value.startswith(base + "bia/") or value.startswith(base + "noi-dung/")


def is_avatar_public_id(value: object) -> bool:
    """Accept new path-style ids under the configured root and legacy UUID ids already stored."""
    if not isinstance(value, str):
        return False
    if _LEGACY_UUID_PUBLIC_ID.fullmatch(value):
        return True
    root = "/".join(_root_segments()) + "/"
    return bool(_PATH_PUBLIC_ID.fullmatch(value)) and value.startswith(root)
